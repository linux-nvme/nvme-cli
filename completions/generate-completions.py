ZSH_HEADER = '''\
#compdef _nvme nvme
# SPDX-License-Identifier: GPL-2.0-or-later
#
# zsh completions for the nvme command-line interface
#
# This file is generated by generate-completions.py. Do not edit.
#
# Note: with verbose completion listings (the default), zsh may report more
# "possibilities" than the number of lines it displays -- e.g. "452
# possibilities" for ~153 commands. This is expected, not duplication: when
# descriptions are shown, _describe lays the matches out in a multi-column grid
# and pads it with empty alignment matches, which count toward the total but
# render as nothing. The count scales with terminal width; the displayed
# entries are correct.
'''

# Helpers emitted inside the _nvme function body (hence the tab indent). Each
# command carries its own options straight from the metadata.
ZSH_HELPERS = '''\
\t# Describe options, giving those ending in '=' no trailing space.
\t#
\t# The tags are 'nvme-noeq-options'/'nvme-eq-options', deliberately NOT the
\t# standard 'options' tag: when a device candidate is also offered (compadd
\t# below), the completion system's handling of the reserved 'options' tag
\t# suppressed the whole group at an empty prefix, so '--help' etc. only appeared
\t# once a '-' was typed. A non-reserved tag sidesteps that.
\t_nvme_describe() {
\t\tlocal desc="$1"
\t\tlocal -a opts=("${(@P)2}")
\t\tlocal -a eq_opts noeq_opts
\t\tlocal opt

\t\tfor opt in "${opts[@]}"; do
\t\t\tif [[ "${opt%%:*}" == *= ]]; then
\t\t\t\teq_opts+=("$opt")
\t\t\telse
\t\t\t\tnoeq_opts+=("$opt")
\t\t\tfi
\t\tdone

\t\t(( ${#noeq_opts} )) && _describe -t nvme-noeq-options "$desc" noeq_opts
\t\t(( ${#eq_opts} )) && _describe -t nvme-eq-options "$desc" eq_opts -S ''
\t}

\t# Complete an option's value from a known set, in both the attached
\t# ('--opt=val', '-o=val') and separate-word ('--opt val', '-o val') forms.
\t# Called once per command with alternating NAMES VALUES arguments: NAMES is a
\t# space-separated spelling list ('--output-format -o'), VALUES its
\t# space-separated value list. Completes the first option whose spelling matches
\t# the word being entered.
\t_nvme_opt_vals() {
\t\tlocal -a names
\t\tlocal name
\t\twhile (( $# >= 2 )); do
\t\t\tnames=(${=1})
\t\t\tfor name in "${names[@]}"; do
\t\t\t\tif [[ ${words[CURRENT]} == ${name}=* ]] || \\
\t\t\t\t   [[ ${words[CURRENT-1]} == "${name}" ]]; then
\t\t\t\t\t_values '' ${=2}
\t\t\t\t\treturn 0
\t\t\t\tfi
\t\t\tdone
\t\t\tshift 2
\t\tdone
\t\treturn 1
\t}

\t# Complete an option's value as a filename, in both the attached
\t# ('--opt=path', '-o=path') and separate-word ('--opt path', '-o path') forms.
\t# Each argument is a space-separated spelling list ('--fw -f'); if the word
\t# being entered is that option's value, offer files. Mirrors the value form of
\t# _nvme_opt_vals.
\t_nvme_opt_files() {
\t\tlocal -a names
\t\tlocal name spec
\t\tfor spec in "$@"; do
\t\t\tnames=(${=spec})
\t\t\tfor name in "${names[@]}"; do
\t\t\t\tif [[ ${words[CURRENT]} == ${name}=* ]]; then
\t\t\t\t\tcompset -P '*='
\t\t\t\t\t_files
\t\t\t\t\treturn 0
\t\t\t\telif [[ ${words[CURRENT-1]} == "${name}" ]]; then
\t\t\t\t\t_files
\t\t\t\t\treturn 0
\t\t\t\tfi
\t\t\tdone
\t\tdone
\t\treturn 1
\t}

\t# True if a device argument is already present, so we do not offer another.
\t# Only words before the one being completed count (the current word may be a
\t# partial '/dev/nvme' the user is still typing).
\t_nvme_has_device() {
\t\tlocal -i i
\t\tfor (( i = 1; i < CURRENT; i++ )); do
\t\t\t[[ ${words[i]} == /dev/nvme* ]] && return 0
\t\tdone
\t\treturn 1
\t}
'''


def zsh_escape(s):
    """Escape a string for inclusion inside a zsh '...' single-quoted string."""
    return (s or "").replace("'", "'\\''")


def zsh_var(plugin, cmd):
    """A unique zsh array-variable name for a command's option list."""
    name = "_"
    if plugin:
        name += plugin.replace("-", "_") + "_"
    name += cmd.replace("-", "_")
    return name


def emit_zsh_value_completions(out, tab, cmd):
    """Emit a single _nvme_opt_vals call listing the command's value-set options
    as alternating spelling/value-list pairs."""
    pairs = [f'"{opt_spellings(o)}" "{" ".join(o["values"])}"'
             for o in command_options(cmd) if o.get("values")]
    if not pairs:
        return
    if len(pairs) == 1:
        out.write(f'{tab}_nvme_opt_vals {pairs[0]} && return\n')
    else:
        # Continuation lines align under the first argument.
        cont = tab + " " * len("_nvme_opt_vals ")
        joined = f" \\\n{cont}".join(pairs)
        out.write(f'{tab}_nvme_opt_vals {joined} && return\n')


def emit_zsh_file_completions(out, tab, cmd):
    """Emit a _nvme_opt_files call for the command's file/directory-valued
    options (those without an enumerated value set)."""
    args = [f'"{opt_spellings(o)}"' for o in command_options(cmd)
            if not o.get("values") and opt_is_file(o)]
    if not args:
        return
    if len(args) == 1:
        out.write(f'{tab}_nvme_opt_files {args[0]} && return\n')
    else:
        cont = tab + " " * len("_nvme_opt_files ")
        joined = f" \\\n{cont}".join(args)
        out.write(f'{tab}_nvme_opt_files {joined} && return\n')


def emit_zsh_command_clause(out, tab, path, cmd):
    """Emit the case clause for one command: its value completions, option
    descriptions, and a device-argument candidate. Aliases share the clause."""
    names = cmd_names(cmd)
    # The primary (whitespace-stripped) name drives the variable and label; a
    # stray space in the C command tables would otherwise leak into both.
    name = names[0]
    # The pattern sits at 'tab'; its body is indented one level deeper.
    body = tab + "\t"
    out.write(f'{tab}({"|".join(names)})\n')

    opts = list(command_options(cmd))
    if not opts:
        # No options to offer, but still complete a device argument.
        out.write(f"{body}_nvme_has_device || compadd -- /dev/nvme*(N)\n")
        out.write(f"{body};;\n\n")
        return

    emit_zsh_value_completions(out, body, cmd)
    emit_zsh_file_completions(out, body, cmd)

    var = zsh_var(path, name)
    out.write(f"{body}local {var}\n{body}{var}=(\n")
    for o in opts:
        desc = zsh_escape(flatten(o.get("description")))
        out.write(f"{body}\t--{o['long']}{opt_suffix(o)}':{desc}'\n")
        if o.get("short"):
            out.write(f"{body}\t-{o['short']}':alias for --{o['long']}'\n")
    # -h/--help is accepted by every command but is not in the metadata option
    # list, so add it explicitly.
    out.write(f"{body}\t--help':show help'\n")
    out.write(f"{body}\t-h':alias for --help'\n")
    out.write(f"{body})\n")
    out.write(f"{body}_arguments '*:: :->subcmds'\n")
    plabel = f"nvme {path + ' ' if path else ''}{name} options"
    out.write(f'{body}_nvme_describe "{plabel}" {var}\n')
    out.write(f"{body}_nvme_has_device || compadd -- /dev/nvme*(N)\n")
    out.write(f"{body};;\n\n")


def generate_zsh(model, out):
    out.write(ZSH_HEADER)
    out.write("\n_nvme () {\n\tlocal -a _cmds\n\t_cmds=(\n")
    for c in builtin_commands(model):
        for n in cmd_names(c):
            out.write(f"\t\t'{n}:{zsh_escape(flatten(c.get('description')))}'\n")
    for p in plugins(model):
        out.write(f"\t\t'{p['name']}:{zsh_escape(flatten(p.get('description')))}'\n")
    for name in BUILTIN_COMMANDS:
        out.write(f"\t\t'{name}'\n")
    out.write("\t)\n\n")

    out.write(ZSH_HELPERS)

    # After the top-level _arguments strips 'nvme', CURRENT counts words within
    # the command: 1 = completing the command name, 2 = a builtin's first
    # option OR a plugin's sub-command name, >=3 = a plugin sub-command's
    # options. Builtin option completion and plugin sub-command listing both
    # happen at CURRENT==2, so the dispatch keys on ${words[1]} without a lower
    # CURRENT guard; each plugin clause splits sub-command listing (CURRENT==2)
    # from sub-command option completion itself.
    out.write("\n\t_arguments '*:: :->subcmds' && return 0\n\n"
              "\tif (( CURRENT == 1 )); then\n"
              "\t\t_describe -t commands \"nvme subcommands\" _cmds\n"
              "\t\treturn\n"
              "\tfi\n\n"
              "\tcase ${words[1]} in\n")

    for p in plugins(model):
        out.write(f"\t\t({p['name']})\n"
                  f"\t\t\tif (( CURRENT == 2 )); then\n"
                  f"\t\t\t\tlocal -a _sub\n\t\t\t\t_sub=(\n")
        for c in p["commands"]:
            desc = zsh_escape(flatten(c.get("description")))
            for n in cmd_names(c):
                out.write(f"\t\t\t\t\t'{n}:{desc}'\n")
        out.write(f"\t\t\t\t)\n"
                  f'\t\t\t\t_describe -t commands "nvme {p["name"]} commands" _sub\n'
                  f"\t\t\t\treturn\n\t\t\tfi\n\n"
                  f"\t\t\tcase ${{words[2]}} in\n")
        for c in p["commands"]:
            emit_zsh_command_clause(out, "\t\t\t\t", p["name"], c)
        out.write("\t\t\t\t(*)\n\t\t\t\t\t_files\n\t\t\t\t\t;;\n")
        out.write("\t\t\tesac\n\t\t\t;;\n\n")

    for c in builtin_commands(model):
        emit_zsh_command_clause(out, "\t\t", None, c)

    # help and version have no metadata command clause. 'help CMD' prints CMD's
    # help, so complete a command name at that one argument (CURRENT==2); past it
    # there is nothing to complete. 'version' takes no argument. Both return
    # rather than fall through to _files.
    out.write('\t\t(help)\n'
              '\t\t\t(( CURRENT == 2 )) && \\\n'
              '\t\t\t\t_describe -t commands "nvme subcommands" _cmds\n'
              '\t\t\treturn\n\t\t\t;;\n\n'
              '\t\t(version)\n'
              '\t\t\treturn\n\t\t\t;;\n\n')

    out.write("\t\t(*)\n\t\t\t_files\n\t\t\t;;\n"
              "\tesac\n}\n")


