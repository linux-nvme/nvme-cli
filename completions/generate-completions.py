GENERATORS = {"bash": generate_bash, "zsh": generate_zsh}


def open_out(path):
    return sys.stdout if path == "-" else open(path, "w")


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("input", nargs="?", default="-",
                    help="JSON model file, or '-' for stdin (default)")
    ap.add_argument("--bash", metavar="FILE",
                    help="write bash completion to FILE ('-' for stdout)")
    ap.add_argument("--zsh", metavar="FILE",
                    help="write zsh completion to FILE ('-' for stdout)")
    args = ap.parse_args()

    requested = [(s, getattr(args, s)) for s in GENERATORS if getattr(args, s)]
    if not requested:
        ap.error("specify at least one of --bash/--zsh")

    # Each shell's script is distinct, so several sharing stdout would just
    # concatenate into one unusable stream. Require a named file per shell when
    # more than one is requested.
    if len(requested) > 1 and any(path == "-" for _, path in requested):
        ap.error("with more than one shell, give each a FILE (not '-'/stdout)")

    if args.input == "-":
        model = json.load(sys.stdin)
    else:
        with open(args.input) as src:
            model = json.load(src)

    version = model.get("schema_version")
    if version != SUPPORTED_SCHEMA_VERSION:
        ap.error(f"unsupported schema_version {version!r} "
                 f"(expected {SUPPORTED_SCHEMA_VERSION})")

    for shell, path in requested:
        out = open_out(path)
        try:
            GENERATORS[shell](model, out)
        finally:
            if out is not sys.stdout:
                out.close()


if __name__ == "__main__":
    main()
