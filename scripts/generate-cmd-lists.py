"""Generate the command lists of nvme(1) from the command metadata.

Writes cmds-main.txt (the built-in commands and the command groups) and
cmd-plugins.txt (the vendor plugins) into DOCDIR. A command links to its
man page if DOCDIR has one. Deprecated commands are left out.

With --check, compare the lists with the ones in DOCDIR instead. A
build without all plugins or without fabrics has fewer commands: then
only the listed commands of the build are checked.

Usage: generate-cmd-lists.py [--check] (--nvme NVME | METADATA) DOCDIR

METADATA is the output of 'nvme utils dump-command-metadata', '-' for
stdin. With --nvme, the metadata is read from that binary.
"""

import argparse
import json
import os
import subprocess
import sys

SUPPORTED_SCHEMA_VERSION = 2

MAIN_FILE = 'cmds-main.txt'
PLUGINS_FILE = 'cmd-plugins.txt'

HEADER = ('// Generated by scripts/generate-cmd-lists.py. Do not edit.\n'
          '// Run: meson compile -C <build-dir> update-cmd-lists\n')

# The command groups of the specification, listed with the main commands.
CORE_PLUGINS = {
    'config', 'dir', 'exclusion', 'fdp', 'feat', 'fw', 'id', 'io-mgmt',
    'keys', 'lm', 'log', 'nbft', 'ns', 'nvme-mi', 'registry', 'resv',
    'rpmb', 'security', 'sed', 'utils', 'zns',
}

VENDOR_PLUGINS = {
    'amzn', 'dapustor', 'dell', 'dera', 'huawei', 'ibm', 'innogrit',
    'inspur', 'intel', 'mangoboost', 'memblaze', 'micron', 'netapp',
    'nvidia', 'ocp', 'samsung', 'seagate', 'sfx', 'shannon', 'sndk',
    'solidigm', 'ssstc', 'toshiba', 'transcend', 'virtium', 'wdc', 'ymtc',
}

# Man pages which are not named after their command.
PAGES = {
    ('feat', 'perf-characteristics'): 'nvme-feat-perfc',
    ('log', 'supported-pages'): 'nvme-supported-log-pages',
    ('micron', 'clear-pcie-correctable-errors'):
        'nvme-micron-clear-pcie-errors',
    ('micron', 'select-download'): 'nvme-micron-selective-download',
    ('micron', 'vs-internal-log'): 'nvme-micron-internal-log',
    ('micron', 'vs-nand-stats'): 'nvme-micron-nand-stats',
    ('micron', 'vs-pcie-stats'): 'nvme-micron-pcie-stats',
    ('micron', 'vs-smart-add-log'): 'nvme-micron-smart-add-log',
    ('micron', 'vs-temperature-stats'): 'nvme-micron-temperature-stats',
    ('ocp', 'clear-pcie-correctable-errors'):
        'nvme-ocp-clear-pcie-correctable-error-counters',
}

# A build without fabrics has no connect command.
FABRICS_COMMAND = 'connect'


def load_metadata(args):
    if args.nvme:
        out = subprocess.run([args.nvme, 'utils', 'dump-command-metadata'],
                             check=True, capture_output=True, text=True)
        return json.loads(out.stdout)
    if args.metadata == '-':
        return json.load(sys.stdin)
    with open(args.metadata) as f:
        return json.load(f)


def entry(docdir, plugin, cmd):
    key = (plugin, cmd['name'])
    page = PAGES.get(key, 'nvme-' + (plugin + '-' if plugin else '') +
                     cmd['name'])
    if os.path.isfile(os.path.join(docdir, page + '.txt')):
        term = f'linknvme:{page}[1]'
    else:
        term = ' '.join(['nvme'] + ([plugin] if plugin else []) +
                        [cmd['name']])
    desc = ' '.join(cmd.get('description', '').split())

    return f'{term}::\n\t{desc}\n'


def entries(docdir, plugin, cmds):
    return [((plugin or '', c['name']), entry(docdir, plugin, c))
            for c in cmds if not c.get('deprecated')]


def generate(meta, docdir):
    main = entries(docdir, None, meta['commands'])
    vendor = []
    for p in meta['plugins']:
        if p['name'] in CORE_PLUGINS:
            main += entries(docdir, p['name'], p['commands'])
        elif p['name'] in VENDOR_PLUGINS:
            vendor += entries(docdir, p['name'], p['commands'])
        else:
            sys.exit(f"plugin '{p['name']}' is not classified in "
                     f'{os.path.basename(__file__)}')

    return {MAIN_FILE: [e for _, e in sorted(main)],
            PLUGINS_FILE: [e for _, e in sorted(vendor)]}


def render(blocks):
    return HEADER + ''.join('\n' + b for b in blocks)


def is_complete(meta):
    plugins = {p['name'] for p in meta['plugins']}
    commands = {c['name'] for c in meta['commands']}

    return (CORE_PLUGINS | VENDOR_PLUGINS) <= plugins and \
        FABRICS_COMMAND in commands


def is_subsequence(blocks, text):
    it = iter(text.removeprefix(HEADER).lstrip('\n').split('\n\n'))
    have = [b.rstrip('\n') for b in blocks]

    return all(any(b == c.rstrip('\n') for c in it) for b in have)


def check(lists, docdir, complete):
    stale = []
    for name, blocks in lists.items():
        try:
            with open(os.path.join(docdir, name)) as f:
                text = f.read()
        except FileNotFoundError:
            text = ''
        if complete:
            ok = text == render(blocks)
        else:
            ok = is_subsequence(blocks, text)
        if not ok:
            stale.append(name)
    for name in stale:
        print(f'{name} is not up to date. Run: '
              'meson compile -C <build-dir> update-cmd-lists',
              file=sys.stderr)

    return 1 if stale else 0


def main():
    parser = argparse.ArgumentParser(
        description='Generate the command lists of nvme(1).')
    parser.add_argument('--check', action='store_true',
                        help='compare with the lists in DOCDIR')
    parser.add_argument('--nvme', help='read the metadata from this binary')
    parser.add_argument('metadata', nargs='?',
                        help="metadata file, '-' for stdin")
    parser.add_argument('docdir', help='the Documentation directory')
    args = parser.parse_args()
    if bool(args.nvme) == bool(args.metadata):
        parser.error('give either --nvme or METADATA')

    meta = load_metadata(args)
    if meta.get('schema_version') != SUPPORTED_SCHEMA_VERSION:
        sys.exit(f"unsupported metadata schema version "
                 f"{meta.get('schema_version')}")

    lists = generate(meta, args.docdir)
    if args.check:
        return check(lists, args.docdir, is_complete(meta))

    if not is_complete(meta):
        sys.exit('the lists need a build with all plugins and fabrics')
    for name, blocks in lists.items():
        with open(os.path.join(args.docdir, name), 'w') as f:
            f.write(render(blocks))

    return 0


if __name__ == '__main__':
    sys.exit(main())
